"""Bakes the Apple Hard Disk 20SC's model number glyphs into silhouette masks.

The number on the drive's front follows the attached image: "20SC" for a
20 MB image, "32SC" for 32 MB. So the digits 0-9 and the letters "SC" are
baked one mask each, every mask cropped to the same band from cap height to
baseline, and the scene sets them side by side.

The photograph's number is in Apple's serif; Times New Roman is the stand-in.

Writes CassoEmuCore/Ui/Scene/DeskSceneHardDiskLabels.h. Run it from anywhere:

    python scripts/modelgen/bake_hd20sc_label.py
"""

import io
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT  = os.path.join(ROOT, "CassoEmuCore", "Ui", "Scene", "DeskSceneHardDiskLabels.h")

FONT = r"C:\Windows\Fonts\times.ttf"
PX   = 64

font   = ImageFont.truetype(FONT, PX)
glyphs = "0123456789SC"
buf    = io.StringIO()


def render(ch):
    im = Image.new("L", (PX * 3, PX * 3), 0)
    ImageDraw.Draw(im).text((PX, PX), ch, fill=255, font=font)
    return im


# The shared band: the tallest ink of any glyph, so every mask has the same
# rows and the digits sit on one baseline.
top, bottom = PX * 3, 0

for ch in glyphs:
    box    = render(ch).getbbox()
    top    = min(top, box[1])
    bottom = max(bottom, box[3])

names = []

for ch in glyphs:
    im   = render(ch)
    box  = im.getbbox()
    im   = im.crop((box[0], top, box[2], bottom))
    rows = ["".join("#" if im.getpixel((x, y)) > 110 else "." for x in range(im.width))
            for y in range(im.height)]
    name = "s_kHdGlyph%s" % ch
    names.append((ch, name, len(rows[0])))

    buf.write("// \"%s\".\n" % ch)
    buf.write("static const char * const  %s[] =\n{\n" % name)

    for r in rows:
        buf.write("    \"%s\",\n" % r)

    buf.write("};\n\n\n")

buf.write("static constexpr int  kHdGlyphRows = %d;\n\n\n" % (bottom - top))
buf.write("struct HdGlyph\n{\n    char                 ch;\n    const char * const * mask;\n    int                  cols;\n};\n\n\n")
buf.write("static const HdGlyph  s_kHdGlyphs[] =\n{\n")

for ch, name, cols in names:
    buf.write("    { '%s', %s, %d },\n" % (ch, name, cols))

buf.write("};\n")

HEADER = '''#pragma once





////////////////////////////////////////////////////////////////////////////////
//
//  DeskSceneHardDiskLabels.h
//
//  The Apple Hard Disk 20SC's model number glyphs as silhouette masks, baked
//  from Times New Roman at %dpx: the digits 0-9 and the letters S and C, each
//  cropped to the same band so they share a baseline when set side by side.
//
//  Rows run top-down and every row of a mask is the same length. '#' is ink.
//
//  GENERATED by scripts/modelgen/bake_hd20sc_label.py. Edit that, not this.
//
////////////////////////////////////////////////////////////////////////////////


''' % PX

with open(OUT, "w", newline="\r\n") as f:
    f.write(HEADER + buf.getvalue())

print("wrote %s" % OUT)
