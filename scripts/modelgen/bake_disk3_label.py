"""Bakes the Disk ///'s drive-number digits into silhouette masks.

The drive label at the top left of a Disk ///'s face reads "disk ///" over
a white field with "DRIVE" and the drive's number. The word and the logotype
are in the model (cad_disk3.py); the number differs per drive and the model
is shared, so the scene stamps it from these masks. The label's type is a
regular-weight grotesque, so the digits are baked from Arial.

Each mask is cropped to the digit's extent, which for these digits is
one cap height.

Writes CassoEmuCore/Ui/Scene/DeskSceneDisk3Labels.h. Run it from anywhere:

    python scripts/modelgen/bake_disk3_label.py
"""

import io
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT  = os.path.join(ROOT, "CassoEmuCore", "Ui", "Scene", "DeskSceneDisk3Labels.h")

FONT = r"C:\Windows\Fonts\arial.ttf"
PX   = 64

font = ImageFont.truetype(FONT, PX)
buf  = io.StringIO()


def emit(ch):
    im = Image.new("L", (PX * 3, PX * 3), 0)
    ImageDraw.Draw(im).text((PX, PX // 2), ch, fill=255, font=font)
    im   = im.crop(im.getbbox())
    rows = ["".join("#" if im.getpixel((x, y)) > 110 else "." for x in range(im.width))
            for y in range(im.height)]
    name = "s_kDisk3Digit%sMask" % ch

    buf.write("// \"%s\".\n" % ch)
    buf.write("static const char * const  %s[] =\n{\n" % name)

    for r in rows:
        buf.write("    \"%s\",\n" % r)

    buf.write("};\n\n")
    buf.write("static constexpr int  k%sRows = %d;\n" % (name[3:], len(rows)))
    buf.write("static constexpr int  k%sCols = %d;\n\n\n" % (name[3:], len(rows[0])))


for digit in "1234":
    emit(digit)

HEADER = '''#pragma once





////////////////////////////////////////////////////////////////////////////////
//
//  DeskSceneDisk3Labels.h
//
//  The Disk /// drive label's numbers 1 to 4 as silhouette masks, baked from
//  Arial at %dpx. Rows run top-down and every row is the same length; '#'
//  is ink.
//
//  GENERATED by scripts/modelgen/bake_disk3_label.py. Edit that, not this.
//
////////////////////////////////////////////////////////////////////////////////


''' % PX

with open(OUT, "w", newline="\r\n") as f:
    f.write(HEADER + buf.getvalue())

print("wrote %s" % OUT)
