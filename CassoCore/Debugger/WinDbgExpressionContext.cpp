#include "Pch.h"

#include "Debugger/WinDbgExpressionContext.h"





////////////////////////////////////////////////////////////////////////////////
//
//  WinDbgExpressionContext::WinDbgExpressionContext
//
////////////////////////////////////////////////////////////////////////////////

WinDbgExpressionContext::WinDbgExpressionContext (const IDebugExpressionContext & inner) :
    m_inner (inner)
{
}





////////////////////////////////////////////////////////////////////////////////
//
//  WinDbgExpressionContext::TryGetRegister
//
////////////////////////////////////////////////////////////////////////////////

bool WinDbgExpressionContext::TryGetRegister (const std::string & name, Word & value) const
{
    return m_inner.TryGetRegister (name, value);
}





////////////////////////////////////////////////////////////////////////////////
//
//  WinDbgExpressionContext::TryPeek
//
////////////////////////////////////////////////////////////////////////////////

bool WinDbgExpressionContext::TryPeek (Word address, Byte & value) const
{
    return m_inner.TryPeek (address, value);
}





////////////////////////////////////////////////////////////////////////////////
//
//  WinDbgExpressionContext::TryResolveSymbol
//
////////////////////////////////////////////////////////////////////////////////

bool WinDbgExpressionContext::TryResolveSymbol (const std::string & name, Word & address) const
{
    return m_inner.TryResolveSymbol (name, address);
}





////////////////////////////////////////////////////////////////////////////////
//
//  WinDbgExpressionContext::GetNumberSyntax
//
////////////////////////////////////////////////////////////////////////////////

NumberSyntax WinDbgExpressionContext::GetNumberSyntax() const
{
    return NumberSyntax::WinDbg;
}





