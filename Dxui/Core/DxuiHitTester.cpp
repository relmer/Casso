#include "Pch.h"

#include "DxuiHitTester.h"





////////////////////////////////////////////////////////////////////////////////
//
//  IsPointInRect
//
////////////////////////////////////////////////////////////////////////////////

bool DxuiHitTester::IsPointInRect (const RECT & r, int x, int y)
{
    return (x >= r.left) && (x < r.right) && (y >= r.top) && (y < r.bottom);
}





////////////////////////////////////////////////////////////////////////////////
//
//  Clear
//
////////////////////////////////////////////////////////////////////////////////

void DxuiHitTester::Clear()
{
    m_rects.clear();
}





////////////////////////////////////////////////////////////////////////////////
//
//  Register
//
////////////////////////////////////////////////////////////////////////////////

void DxuiHitTester::Register (const DxuiHitRect & rect)
{
    m_rects.push_back (rect);
}





////////////////////////////////////////////////////////////////////////////////
//
//  Pick
//
//  Walks registrations in reverse-insert order so later registrations
//  (which render on top) take precedence on hit ties.
//
////////////////////////////////////////////////////////////////////////////////

const DxuiHitRect * DxuiHitTester::Pick (int xClient, int yClient) const
{
    const DxuiHitRect *  hit = nullptr;
    auto                 it  = m_rects.rbegin();



    // Reverse order, so the topmost registration wins; the found test in the
    // condition stops the walk at it.
    for ( ; hit == nullptr && it != m_rects.rend(); ++it)
    {
        if (IsPointInRect (it->rect, xClient, yClient))
        {
            hit = &(*it);
        }
    }

    return hit;
}
