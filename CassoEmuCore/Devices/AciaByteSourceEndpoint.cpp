#include "Pch.h"

#include "Devices/AciaByteSourceEndpoint.h"
#include "Devices/Acia6551.h"





////////////////////////////////////////////////////////////////////////////////
//
//  AciaByteSourceEndpoint
//
////////////////////////////////////////////////////////////////////////////////

AciaByteSourceEndpoint::AciaByteSourceEndpoint (Acia6551 * acia, vector<Byte> bytes)
    : m_acia  (acia),
      m_bytes (move (bytes))
{
}





////////////////////////////////////////////////////////////////////////////////
//
//  Start
//
////////////////////////////////////////////////////////////////////////////////

void AciaByteSourceEndpoint::Start()
{
    if (m_acia != nullptr)
    {
        m_acia->EnqueueReceivedBytes (m_bytes.data(), m_bytes.size());
    }
}





////////////////////////////////////////////////////////////////////////////////
//
//  OnByteTransmitted
//
//  A file attachment only sends; transmitted bytes are discarded.
//
////////////////////////////////////////////////////////////////////////////////

void AciaByteSourceEndpoint::OnByteTransmitted (Byte value)
{
    (void) value;
}
