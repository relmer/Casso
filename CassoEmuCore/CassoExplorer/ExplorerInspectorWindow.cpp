////////////////////////////////////////////////////////////////////////////////

ExplorerInspectorWindow::ExplorerInspectorWindow() :
    m_window (std::make_unique<DiskInspectorWindow>())
{
}





////////////////////////////////////////////////////////////////////////////////
//
//  ExplorerInspectorWindow::~ExplorerInspectorWindow
//
////////////////////////////////////////////////////////////////////////////////

ExplorerInspectorWindow::~ExplorerInspectorWindow() = default;





////////////////////////////////////////////////////////////////////////////////
//
//  ExplorerInspectorWindow::Create
//
//  The window is activated, since the user just chose Inspect, and is given
//  the Explorer window's icon.
//
////////////////////////////////////////////////////////////////////////////////

HRESULT ExplorerInspectorWindow::Create (HINSTANCE hInstance, HWND anchor, const DxuiTheme * theme, IDiskInspectorHost * host)
{
    HRESULT  hr   = S_OK;
    HICON    icon = nullptr;



    hr = m_window->Create (hInstance, anchor, theme, host, true);
    CHR (hr);

    icon = (anchor != nullptr) ? reinterpret_cast<HICON> (SendMessageW (anchor, WM_GETICON, ICON_BIG, 0)) : nullptr;

    if (icon != nullptr)
    {
        SendMessageW (m_window->GetHwnd(), WM_SETICON, ICON_BIG, reinterpret_cast<LPARAM> (icon));
    }

Error:
    return hr;
}





////////////////////////////////////////////////////////////////////////////////
//
//  ExplorerInspectorWindow::Front
//
////////////////////////////////////////////////////////////////////////////////

void ExplorerInspectorWindow::Front()
{
    BOOL  isFront = FALSE;



    m_window->Show (true);
    isFront = SetForegroundWindow (m_window->GetHwnd());
    IGNORE_RETURN_VALUE (isFront, TRUE);
}





