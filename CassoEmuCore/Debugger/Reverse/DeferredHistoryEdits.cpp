#include "Pch.h"

#include "Debugger/Reverse/DeferredHistoryEdits.h"





////////////////////////////////////////////////////////////////////////////////
//
//  DeferredHistoryEdits::Defer
//
////////////////////////////////////////////////////////////////////////////////

bool DeferredHistoryEdits::Defer (const DebugCommand & command)
{
    std::lock_guard<std::mutex>  guard   (m_lock);
    bool                         isFirst = m_edits.empty();



    m_edits.push_back (command);
    return isFirst;
}





////////////////////////////////////////////////////////////////////////////////
//
//  DeferredHistoryEdits::HasAny
//
////////////////////////////////////////////////////////////////////////////////

bool DeferredHistoryEdits::HasAny() const
{
    std::lock_guard<std::mutex>  guard (m_lock);



    return !m_edits.empty();
}





////////////////////////////////////////////////////////////////////////////////
//
//  DeferredHistoryEdits::TakeAll
//
////////////////////////////////////////////////////////////////////////////////

std::vector<DebugCommand> DeferredHistoryEdits::TakeAll()
{
    std::lock_guard<std::mutex>  guard (m_lock);
    std::vector<DebugCommand>    edits;



    edits.swap (m_edits);
    return edits;
}





////////////////////////////////////////////////////////////////////////////////
//
//  DeferredHistoryEdits::Clear
//
////////////////////////////////////////////////////////////////////////////////

void DeferredHistoryEdits::Clear()
{
    std::lock_guard<std::mutex>  guard (m_lock);



    m_edits.clear();
}




