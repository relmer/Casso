#include "Pch.h"

#include "Debugger/Reverse/HistorySpan.h"





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::Start
//
//  Recording starts with the machine live. A pause chosen before the start
//  applies from the first keyframe on.
//
////////////////////////////////////////////////////////////////////////////////

void HistorySpan::Start()
{
    m_isRecording = true;
    m_isLive      = true;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::Stop
//
//  The pause stays as the user chose it.
//
////////////////////////////////////////////////////////////////////////////////

void HistorySpan::Stop()
{
    m_isRecording   = false;
    m_isLive        = true;
    m_isEditPending = false;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::SetPaused
//
////////////////////////////////////////////////////////////////////////////////

bool HistorySpan::SetPaused (bool isPaused)
{
    bool  isChanged = isPaused != m_isPaused;



    m_isPaused = isPaused;

    return isChanged;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::Leave
//
////////////////////////////////////////////////////////////////////////////////

bool HistorySpan::Leave (uint64_t position, uint64_t cycle)
{
    if (!m_isLive)
    {
        return false;
    }

    m_liveEndPosition = position;
    m_liveEndCycle    = cycle;
    m_isLive          = false;

    return true;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::BecomeLive
//
////////////////////////////////////////////////////////////////////////////////

void HistorySpan::BecomeLive (uint64_t position)
{
    m_isLive    = true;
    m_hereStart = 0;
    m_hereEnd   = 0;

    NotePause (position);
}





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::NotePause
//
////////////////////////////////////////////////////////////////////////////////

void HistorySpan::NotePause (uint64_t position)
{
    if (m_isPaused)
    {
        m_pauseStart = position;
    }
}





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::TakeEdit
//
////////////////////////////////////////////////////////////////////////////////

bool HistorySpan::TakeEdit()
{
    bool  isPending = m_isEditPending;



    m_isEditPending = false;

    return isPending;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HistorySpan::GetRecordedEnd
//
////////////////////////////////////////////////////////////////////////////////

uint64_t HistorySpan::GetRecordedEnd (uint64_t position) const
{
    return (m_isLive && m_isPaused) ? m_pauseStart : GetLiveEndPosition (position);
}
