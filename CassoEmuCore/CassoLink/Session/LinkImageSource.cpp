#include "Pch.h"

#include "CassoLink/Session/LinkImageSource.h"
#include "Devices/Disk/IDiskFileIo.h"





////////////////////////////////////////////////////////////////////////////////
//
//  FileImageSource::ReadImage
//
////////////////////////////////////////////////////////////////////////////////

HRESULT FileImageSource::ReadImage (std::vector<Byte> & outBytes)
{
    return m_io.ReadAllBytes (m_path, outBytes);
}





////////////////////////////////////////////////////////////////////////////////
//
//  FileImageSource::GetName
//
////////////////////////////////////////////////////////////////////////////////

std::string FileImageSource::GetName() const
{
    return std::filesystem::path (m_path).filename().string();
}
