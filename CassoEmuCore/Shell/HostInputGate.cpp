#include "Pch.h"

#include "Shell/HostInputGate.h"





////////////////////////////////////////////////////////////////////////////////
//
//  HostInputGate::TryEnter
//
//  Takes the gate shared into lock and says whether the host may write. The
//  caller keeps lock while it writes; on false it writes nothing.
//
////////////////////////////////////////////////////////////////////////////////

bool HostInputGate::TryEnter (std::shared_lock<std::shared_mutex> & lock)
{
    lock = std::shared_lock<std::shared_mutex> (m_mutex);

    return !m_isHeld;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HostInputGate::Hold
//
////////////////////////////////////////////////////////////////////////////////

void HostInputGate::Hold()
{
    std::unique_lock<std::shared_mutex>  lock (m_mutex);



    m_isHeld = true;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HostInputGate::Release
//
////////////////////////////////////////////////////////////////////////////////

void HostInputGate::Release()
{
    std::unique_lock<std::shared_mutex>  lock (m_mutex);



    m_isHeld = false;
}





////////////////////////////////////////////////////////////////////////////////
//
//  HostInputGate::IsHeld
//
////////////////////////////////////////////////////////////////////////////////

bool HostInputGate::IsHeld() const
{
    std::shared_lock<std::shared_mutex>  lock (m_mutex);



    return m_isHeld;
}





