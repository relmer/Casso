#include "Pch.h"

#include "Devices/Tape/ITapeDeckPort.h"
#include "Machines/Apple2/Common/CassettePort.h"





////////////////////////////////////////////////////////////////////////////////
//
//  CassettePort
//
////////////////////////////////////////////////////////////////////////////////

CassettePort::CassettePort (MemoryBus * bus) :
    m_bus (bus)
{
}





////////////////////////////////////////////////////////////////////////////////
//
//  Read
//
//  $C020-$C02F: toggles the output. Nothing drives the data bus here, so the
//  read returns what the bus already held.
//
////////////////////////////////////////////////////////////////////////////////

Byte CassettePort::Read (Word address)
{
    UNREFERENCED_PARAMETER (address);

    ToggleOutput();

    return m_bus != nullptr ? m_bus->GetFloatingBusValue() : 0;
}





////////////////////////////////////////////////////////////////////////////////
//
//  Write
//
////////////////////////////////////////////////////////////////////////////////

void CassettePort::Write (Word address, Byte value)
{
    UNREFERENCED_PARAMETER (address);
    UNREFERENCED_PARAMETER (value);

    ToggleOutput();
}





////////////////////////////////////////////////////////////////////////////////
//
//  Reset
//
////////////////////////////////////////////////////////////////////////////////

void CassettePort::Reset()
{
    m_outputLevel = false;
}





////////////////////////////////////////////////////////////////////////////////
//
//  SoftReset
//
//  The flip-flop is not on the reset line; only power-up clears it.
//
////////////////////////////////////////////////////////////////////////////////

void CassettePort::SoftReset()
{
}





////////////////////////////////////////////////////////////////////////////////
//
//  ToggleOutput
//
////////////////////////////////////////////////////////////////////////////////

void CassettePort::ToggleOutput()
{
    m_outputLevel = !m_outputLevel;

    if (m_deck != nullptr)
    {
        m_deck->OnOutputToggle (GetCycle());
    }
}





////////////////////////////////////////////////////////////////////////////////
//
//  ReadInputLevel
//
//  Low with nothing plugged in or nothing playing.
//
////////////////////////////////////////////////////////////////////////////////

bool CassettePort::ReadInputLevel()
{
    return m_deck != nullptr && m_deck->ReadInputLevel (GetCycle());
}





////////////////////////////////////////////////////////////////////////////////
//
//  ReadInputOverFloatingBus
//
//  The ][ and ][+ drive only bit 7 at $C060; bits 0-6 are whatever the bus
//  last held.
//
////////////////////////////////////////////////////////////////////////////////

Byte CassettePort::ReadInputOverFloatingBus()
{
    Byte  floating = m_bus != nullptr ? m_bus->GetFloatingBusValue() : 0;



    return (Byte) ((floating & ~kInputBit) | (ReadInputLevel() ? kInputBit : 0));
}





////////////////////////////////////////////////////////////////////////////////
//
//  GetCycle
//
////////////////////////////////////////////////////////////////////////////////

uint64_t CassettePort::GetCycle() const
{
    return m_cycleSource != nullptr ? *m_cycleSource : 0;
}





////////////////////////////////////////////////////////////////////////////////
//
//  Create
//
////////////////////////////////////////////////////////////////////////////////

unique_ptr<MemoryDevice> CassettePort::Create (const DeviceConfig & config, MemoryBus & bus)
{
    UNREFERENCED_PARAMETER (config);

    return make_unique<CassettePort> (&bus);
}
